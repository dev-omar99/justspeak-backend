#!/usr/bin/env python3
"""Generate src/ai-partner/content/curriculum/vocabulary.ts.

Per programme and level: the words that first appear at that level (not at an earlier level), each with a
frequency tier and the first lesson id that uses it, sorted easiest first; plus a phrase bank (the rubric labels
in order of first use). Tiers come from wordfreq Zipf values measured at build time; the wordfreq list itself is
NOT stored (see docs/curriculum-vocabulary-method.md for sources and licences).
Tier 1: Zipf >= 5.0, 2: 4.5-5.0, 3: 4.0-4.5, 4: 3.5-4.0, 5: below 3.5.
"""
import json
from wordfreq import zipf_frequency
from audit_progression import ROOT, LEVELS, load, words

def tier(z): return 1 if z >= 5 else 2 if z >= 4.5 else 3 if z >= 4 else 4 if z >= 3.5 else 5

out = {}
for f in sorted(ROOT.glob('*.ts')):
    if f.name in ('index.ts', 'types.ts', 'vocabulary.ts') or f.name.endswith('.spec.ts'): continue
    d = load(f); seen = set(); lv_out = {}
    for lv in LEVELS:
        new = {}; phrases = []
        for l in d['levels'][lv]:
            for w in words(' '.join([l['title'], l['goal']] + [r['label'] for r in l['rubric']])):
                if w not in seen and w not in new: new[w] = l['id']
            for r in l['rubric']:
                if r['label'] not in phrases: phrases.append(r['label'])
        seen |= set(new)
        ws = sorted(((w, zipf_frequency(w, 'en'), i) for w, i in new.items()), key=lambda x: (-x[1], x[0]))
        lv_out[lv] = {'words': [{'word': w, 'tier': tier(z), 'firstLessonId': i} for w, z, i in ws], 'phrases': phrases}
    out[d['id']] = lv_out
hdr = '''/**
 * GENERATED by scripts/curriculum/build_vocabulary.py. Do not edit by hand.
 * Target words and phrases per programme and level, easiest first (tier 1 = most frequent).
 * Sources: our own lesson text; frequency tiers measured with wordfreq (CC BY-SA 4.0 data), list not stored.
 * See docs/curriculum-vocabulary-method.md. Hidden draft, admin preview only.
 */
export type VocabularyTier = 1 | 2 | 3 | 4 | 5;
export interface VocabularyWord { word: string; tier: VocabularyTier; firstLessonId: string }
export interface LevelVocabulary { words: VocabularyWord[]; phrases: string[] }
export const CURRICULUM_VOCABULARY: Record<string, Record<string, LevelVocabulary>> = '''
(ROOT / 'vocabulary.ts').write_text(hdr + json.dumps(out, indent=1) + ';\n')
for p, v in out.items(): print(p, {k: len(x['words']) for k, x in v.items()})
